from __future__ import annotations

from dataclasses import asdict, dataclass
from datetime import datetime
import json
from pathlib import Path
from typing import Iterable

from atlas.autonomous_mission_scheduler import AutonomousMissionScheduler, MissionCandidate, SchedulerResult
from atlas.economic_feedback_reallocator import EconomicFeedbackReallocator, MissionEconomics, PortfolioReallocation
from atlas.economic_outcome_ledger import EconomicOutcome, EconomicOutcomeLedger, EconomicSummary
from atlas.live_mission_runner import ControlledLiveMissionRunner, LiveMissionResult, MissionInput
from atlas.real_market_experiment import (
    MarketExperimentResult,
    MarketObservation,
    OutreachDraft,
    Prospect,
    RealMarketExperimentLoop,
)


@dataclass(frozen=True)
class CommercialBenchmarkResult:
    benchmark_id: str
    live_mission: LiveMissionResult
    market_experiment: MarketExperimentResult
    economic_summary: EconomicSummary
    reallocation: PortfolioReallocation
    schedule: SchedulerResult
    demonstrated_chain: tuple[str, ...]
    blocking_reasons: tuple[str, ...]


class CommercialBenchmarkRunner:
    """Execute one auditable vertical commercial-learning cycle.

    External adapters remain bounded by ControlledLiveMissionRunner. This class only
    connects existing validated components and does not send email or spend money.
    """

    def __init__(self) -> None:
        self.live_runner = ControlledLiveMissionRunner()
        self.market_loop = RealMarketExperimentLoop()
        self.ledger = EconomicOutcomeLedger()
        self.reallocator = EconomicFeedbackReallocator()
        self.scheduler = AutonomousMissionScheduler(maximum_concurrent_missions=1)

    def run(
        self,
        *,
        benchmark_id: str,
        mission: MissionInput,
        opportunity_id: str,
        web_adapter,
        gmail_adapter,
        prospect_adapter,
        prospects: Iterable[Prospect],
        observations: Iterable[MarketObservation],
        outcomes: Iterable[EconomicOutcome],
        total_budget: float,
        priority_score: float = 0.8,
        strategic_fit: float = 0.8,
        now: datetime | None = None,
    ) -> CommercialBenchmarkResult:
        if not benchmark_id.strip() or not opportunity_id.strip():
            raise ValueError("benchmark_id and opportunity_id are required")

        live = self.live_runner.run(
            mission,
            web_adapter=web_adapter,
            gmail_adapter=gmail_adapter,
            prospect_adapter=prospect_adapter,
        )

        qualified = tuple(prospects)
        live_ids = {action.prospect_id for action in live.approval_actions}
        prospect_ids = {item.prospect_id for item in qualified}
        if live_ids and not live_ids.issubset(prospect_ids):
            raise ValueError("live mission actions reference prospects missing from benchmark input")

        drafts = tuple(
            OutreachDraft(
                prospect_id=action.prospect_id,
                subject=action.subject,
                body=action.body,
                authorization=action.authorization,
                rationale="generated by controlled live mission and still requires approval",
            )
            for action in live.approval_actions
        )
        market = self.market_loop.evaluate(opportunity_id, qualified, drafts, tuple(observations))
        economic = self.ledger.summarize(opportunity_id, tuple(outcomes))

        decision_map = {
            "continue": "continue",
            "revise": "hold",
            "stop": "stop",
            "accelerate": "accelerate",
        }
        economics = MissionEconomics(
            mission_id=mission.mission_id,
            sample_size=economic.leads + economic.quotes + economic.orders + economic.losses,
            booked_revenue=economic.booked_revenue,
            booked_gross_profit=economic.booked_gross_profit,
            expected_gross_profit=economic.expected_gross_profit,
            conversion_rate=economic.quote_to_order_rate,
            current_budget=total_budget,
            strategic_fit=strategic_fit,
        )
        reallocation = self.reallocator.reallocate([economics], total_budget=total_budget)
        allocation = reallocation.allocations[0]

        schedule = self.scheduler.schedule(
            [
                MissionCandidate(
                    mission_id=mission.mission_id,
                    priority_score=priority_score,
                    allocated_budget=allocation.allocated_budget,
                    expected_gross_profit=max(economic.expected_gross_profit, 0.0),
                    economic_decision=decision_map[economic.decision],
                    consecutive_no_progress_cycles=0 if market.positive_signals else 1,
                )
            ],
            total_budget=total_budget,
            now=now,
        )

        demonstrated = ["live_mission", "market_learning", "economic_measurement", "budget_reallocation", "next_mission_selection"]
        blocking: list[str] = []
        if live.qualified_prospects == 0:
            blocking.append("no qualified prospect demonstrated")
        if not live.approval_actions:
            blocking.append("no approval-gated Gmail draft demonstrated")
        if market.responses == 0:
            blocking.append("no real prospect response demonstrated")
        if economic.quotes == 0 and economic.orders == 0:
            blocking.append("no quote or order demonstrated")
        if economic.booked_revenue <= 0:
            blocking.append("no booked revenue demonstrated")

        return CommercialBenchmarkResult(
            benchmark_id=benchmark_id,
            live_mission=live,
            market_experiment=market,
            economic_summary=economic,
            reallocation=reallocation,
            schedule=schedule,
            demonstrated_chain=tuple(demonstrated),
            blocking_reasons=tuple(blocking),
        )

    def write(self, result: CommercialBenchmarkResult, output_path: str | Path) -> str:
        path = Path(output_path)
        path.parent.mkdir(parents=True, exist_ok=True)
        payload = {"schema_version": "1.0", "commercial_benchmark": asdict(result)}
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
        return str(path)
